import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {createElement as h} from 'react';
import {renderToStaticMarkup as render} from 'react-dom/server';
import * as UI from '../dist/index.js';
const root=fileURLToPath(new URL('../',import.meta.url));
for(const name of ['Button','Dialog','Drawer','TreeView','HierarchyFlow','NodeGraph','NodeCard','CanvasViewport','ResizableSplit','NumericSeriesEditor','LinePlot','StartupScreen','MenuBar','Icon','RangeField','Switch'])assert.equal(typeof UI[name]==='function'||typeof UI[name]==='object',true,name+' missing');
assert.match(render(h(UI.Button,{disabled:true},'save')),/disabled/);
assert.match(render(h(UI.NumberInput,{label:'Length',unit:'mm',optional:true,onChange(){}})),/placeholder="—"/);
assert.match(render(h(UI.SaveIndicator,{saved:true})),/role="status"/);
assert.match(render(h(UI.Switch,{label:'Snap',checked:true,onChange(){}})),/role="switch"/);
assert.match(render(h(UI.NodeCard,{title:'Mass',value:'0.3 kg',selected:true})),/aria-pressed="true"/);
const pkg=JSON.parse(readFileSync(root+'package.json','utf8'));
for(const entry of Object.values(pkg.exports))for(const file of typeof entry==='string'?[entry]:Object.values(entry))assert.ok(existsSync(root+file),file);
assert.ok(readFileSync(root+'src/Michroma-Regular.ttf').length>60000);
assert.ok(!readFileSync(root+'dist/index.js','utf8').includes('React.createElement'));
assert.ok(existsSync(root+'OFL-Michroma.txt'));
console.log('PASS: compiled package exports, standalone server render, control semantics, font and license assets');
